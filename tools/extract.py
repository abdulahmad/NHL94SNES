def category(name):
    if name.endswith('.spc'):
        return 'sound'
    if '.pal' in name:
        return 'gfx/Pals'
    if (name.startswith('Card') or name.startswith('NoPic')) and '.lin.' in name and name != 'CardBackTiles.lin.pairs':
        return 'gfx/PlayerCards'      # the player photos of PlayerPhotoTable
    return 'gfx'
def rom_offset(a): return ((a >> 16) & 0x7F) * 0x8000 + (a & 0x7FFF)
def sha1_of(data): return hashlib.sha1(data).hexdigest()
TEAM_LIST = 0x9CA5E7
def read_team_names(rom):
    """The player names and team nicknames of the ROM, in the order of the team records. TeamList holds 28 long pointers to the
    team records. A record starts with word offsets, the first leads to the players: each is a length word that counts itself and
    the name, the name and 8 rating bytes; an empty String (length word 2) ends them. Then come four Strings (length word that
    counts itself, then the text): city, abbreviation, nickname, arena."""
    word = lambda a: rom[a] | (rom[a + 1] << 8)
    lst = rom_offset(TEAM_LIST)
    records = sorted(rom_offset(int.from_bytes(rom[lst + 4 * i:lst + 4 * i + 4], 'little')) for i in range(28))
    players, nicknames = [], []
    for rec in records:
        pos = rec + word(rec)
        while word(pos) > 2:
            players.append(rom[pos + 2:pos + word(pos)].decode('latin1'))
            pos += word(pos) + 8
        pos += 2                                   # the empty String that ends the players
        for k in range(4):
            if k == 2 and word(pos) > 2: nicknames.append(rom[pos + 2:pos + word(pos)].decode('latin1'))
            pos += word(pos)
    return players, nicknames
